#!/usr/bin/env python3
"""Write the per-face evidence table into index.html as the SOURCES block.

For every block face: the City's Pedestrian Plan Figure 4 class
(data/field/fig4_face_categories.csv), the tile2net imagery result where an
imagery run covers the face (data/tile2net/eval/face_scores.csv), any Street
View / field audit (data/field/streetview_audit_*.csv), and a one-line
presence status derived from them. The map's block-face popup reads this
table so a reader sees every source for the claim, not just the model.

Usage: python3 tools/inject_sources.py
"""
import glob, json, pathlib, re
import pandas as pd

ROOT = pathlib.Path(__file__).resolve().parents[1]


def status(r):
    sv, f4, t2n = r.get('sv'), r.get('f4'), r.get('t2n')
    if sv == 'no_sidewalk': return 'no sidewalk (Street View check)'
    if sv == 'sidewalk' and f4 == 'no_sidewalk': return 'sidewalk present (Street View); City 2020 map shows none - map predates 2019 sidewalk work'
    if sv == 'sidewalk': return 'sidewalk present (Street View check)'
    if f4 == 'no_sidewalk': return 'City 2020 map: no sidewalk on this street - side not verified'
    if f4 in ('none', 'no_data', 'trail', None): return 'City 2020 map: no sidewalk data here'
    if t2n is False: return 'City map shows a sidewalk; 2023 imagery finds none - unverified'
    if t2n is True: return 'sidewalk (City map and 2023 imagery agree)'
    return 'sidewalk (City map); imagery not yet run here'


def main():
    f4 = pd.read_csv(ROOT / 'data/field/fig4_face_categories.csv').set_index('face')
    out = {}
    for fid, r in f4.iterrows():
        out[fid] = {'f4': r.fig4, 'f4s': float(r.fig4_share)}
    p = ROOT / 'data/tile2net/eval/face_scores.csv'
    if p.exists():
        for fid, r in pd.read_csv(p).set_index('face').iterrows():
            if fid in out:
                out[fid].update({'t2n': bool(r.t2n_sidewalk), 'cov': float(r.t2n_cover),
                                 'w': None if pd.isna(r.t2n_width_ft) else round(float(r.t2n_width_ft), 1), 'area': r.area})
    for p in sorted(glob.glob(str(ROOT / 'data/field/streetview_audit_*.csv'))):
        for fid, r in pd.read_csv(p).set_index('face').iterrows():
            if fid in out:
                out[fid].update({'sv': r.observed, 'svd': str(r.imagery_date), 'svn': str(r.note), 'svw': str(r.checked_on)})
    for fid in out: out[fid]['st'] = status(out[fid])
    block = ('/* SOURCES:BEGIN - generated by tools/inject_sources.py, do not edit by hand */\n'
             'var SOURCES = ' + json.dumps(out, separators=(',', ':')) + ';\n'
             '/* SOURCES:END */')
    html = (ROOT / 'index.html').read_text(encoding='utf-8')
    if 'SOURCES:BEGIN' in html:
        html = re.sub(r'/\* SOURCES:BEGIN.*?SOURCES:END \*/', lambda m: block, html, flags=re.S)
    else:
        html = html.replace('/* CAMPABLE_ALT:BEGIN', block + '\n/* CAMPABLE_ALT:BEGIN', 1)
    (ROOT / 'index.html').write_text(html, encoding='utf-8')
    counts = pd.Series([v['st'] for v in out.values()]).value_counts()
    print(len(out), 'faces ->', 'SOURCES block'); print(counts.to_string())


if __name__ == '__main__':
    main()
